// 선택표가 정본. check/sync는 날짜로 CI를 깨지 않으며 assign은 최신 증거 없이는 거부한다.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const TABLE = "docs/development/agent-models.json";
const tiers = ["light", "balanced", "advanced"];
const efforts = ["low", "medium", "high", "xhigh", "max", "ultra"];
const instruction = "Read AGENTS.md, .agents/skills/develop-agent-app/SKILL.md, docs/START-HERE.md and the assigned ticket. Follow docs/development/workflow.md for model selection, handoff and review. Report actual model and effort; stop on mismatch or unsupported selection. Do only the assigned role and scope.";
const quote = JSON.stringify;

export function validate(table) {
  if (table.schemaVersion !== 1 || !Number.isInteger(table.refreshDays) || table.refreshDays < 1) throw Error("선택표 schema/refreshDays 오류");
  for (const client of ["codex-cli", "codex-desktop", "claude-cli"]) {
    const c = table.clients?.[client];
    if (!c?.version || !c.context || !c.evidence || !/^\d{4}-\d{2}-\d{2}$/.test(c.checkedAt) || !Number.isFinite(Date.parse(c.checkedAt)) || new Date(c.checkedAt).toISOString().slice(0, 10) !== c.checkedAt) throw Error(`${client}: 버전/문맥/근거/확인일 누락`);
    if (Object.keys(c.models ?? {}).sort().join() !== [...tiers].sort().join()) throw Error(`${client}: 잘못된 등급`);
    for (const tier of tiers) {
      const m = c.models[tier];
      if (!m.model || m.model === "inherit" || !/^[a-z0-9][a-z0-9.-]*$/.test(m.model)) throw Error(`${client}/${tier}: 모델 누락 또는 상속`);
      if (!Array.isArray(m.efforts) || m.efforts.some((e) => !efforts.includes(e)) || new Set(m.efforts).size !== m.efforts.length) throw Error(`${client}/${tier}: 잘못된 effort`);
      if (m.defaultEffort === null ? m.efforts.length > 0 || client !== "claude-cli" : !m.efforts.includes(m.defaultEffort)) throw Error(`${client}/${tier}: 지원하지 않는 기본 effort`);
      if (!["confirmed", "pending"].includes(m.capability) || !["baseline", "passed", "pending"].includes(m.evaluation) || !m.evidence || !m.replaceWhen || !["pending", "direct-confirmed", "native-confirmed"].includes(m.nativeExecution) || (m.nativeExecution !== "pending" && !m.executionEvidence)) throw Error(`${client}/${tier}: 검증 상태/근거/대체 조건 누락`);
      if (m.evaluation === "passed" && ["implementation", "review", "quality", "cost"].some((key) => !m.evaluationEvidence?.[key])) throw Error(`${client}/${tier}: 신규 후보 평가 증거 누락`);
      if (client === "claude-cli" && m.capability === "confirmed" && !m.resolvedModel) throw Error(`${client}/${tier}: 확인한 실제 모델 누락`);
    }
  }
  return table;
}

export function generated(table) {
  validate(table);
  const files = {};
  for (const tier of tiers) {
    const name = `task-${tier}`;
    const a = table.clients["codex-cli"].models[tier];
    files[`.codex/agents/${name}.toml`] = `# Generated by scripts/agent-models.mjs sync. Use direct launch for a different effort.\nname = ${quote(name)}\ndescription = ${quote(`${tier} tier; role comes from the ticket`)}\nmodel = ${quote(a.model)}\nmodel_reasoning_effort = ${quote(a.defaultEffort)}\ndeveloper_instructions = ${quote(instruction)}\n`;
    const b = table.clients["claude-cli"].models[tier];
    files[`.claude/agents/${name}.md`] = `---\nname: ${name}\ndescription: ${tier} tier; role comes from the ticket\nmodel: ${b.model}\n---\n\n${instruction}\n\nRun the assignment preflight before starting. Set effort through the verified CLI --effort path; this definition does not claim support for an effort frontmatter field.\n`;
  }
  const a = table.clients["codex-cli"].models.balanced;
  files[".codex/config.toml"] = `# Generated project subagent defaults; the main session model is unchanged.\n# Preflight is mandatory; defaults alone do not check freshness/account support.\n[agents]\ndefault_subagent_model = ${quote(a.model)}\ndefault_subagent_reasoning_effort = ${quote(a.defaultEffort)}\n`;
  return files;
}

export function check(root, table) {
  return Object.entries(generated(table)).flatMap(([file, expected]) => {
    const actual = existsSync(path.join(root, file)) ? readFileSync(path.join(root, file), "utf8") : "";
    const mismatch = file === ".codex/config.toml" ? defaults(actual).join() !== defaults(expected).join() : actual !== expected;
    return mismatch ? [`${file}: 선택표와 native 설정 불일치; node scripts/agent-models.mjs sync`] : [];
  });
}

// 이 편집기는 단일행 문자열/주석만 지원한다. 문자열 속 테이블을 줄 기준으로
// 오인하지 않도록 TOML lexical 문맥에서 여러 줄 문자열을 발견하면 먼저 거부한다.
function assertEditableToml(text) {
  let string = null;
  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    if (string) {
      if (char === "\n") throw Error("단일행 TOML 문자열이 닫히지 않음: 수동 정리 필요");
      if (string === '"' && char === "\\") i++;
      else if (char === string) string = null;
    } else if (char === "#") {
      while (i < text.length && text[i] !== "\n") i++;
    } else if (char === '"' || char === "'") {
      if (text.slice(i, i + 3) === char.repeat(3)) throw Error("여러 줄 TOML 문자열은 안전 편집 미지원: 설정을 변경하지 않음");
      string = char;
    }
  }
  if (string) throw Error("단일행 TOML 문자열이 닫히지 않음: 수동 정리 필요");
  if (text.split("\n").filter((line) => /^\s*\[agents\]\s*(?:#.*)?$/.test(line)).length > 1) throw Error("중복 [agents] 설정: 수동 정리 필요");
}

function defaults(text) {
  assertEditableToml(text);
  let inAgents = false;
  return text.split("\n").flatMap((line) => {
    if (/^\s*\[/.test(line)) inAgents = /^\s*\[agents\]\s*(?:#.*)?$/.test(line);
    return inAgents && /^\s*default_subagent_(?:model|reasoning_effort)\s*=/.test(line) ? [line.trim()] : [];
  }).sort();
}

export function sync(root, table) {
  // 모든 변경을 준비하고 config의 안전성을 확인한 뒤 쓴다. 거부 시 native 파일도 보존한다.
  const changes = Object.entries(generated(table)).map(([file, expected]) => {
    const target = path.join(root, file);
    const actual = existsSync(target) ? readFileSync(target, "utf8") : "";
    let content = expected;
    if (file === ".codex/config.toml" && actual) {
      assertEditableToml(actual);
      let inAgents = false;
      let found = false;
      content = actual.split("\n").flatMap((line) => {
        if (/^\s*\[/.test(line)) {
          inAgents = /^\s*\[agents\]\s*(?:#.*)?$/.test(line);
          if (inAgents) {
            if (found) throw Error("중복 [agents] 설정: 수동 정리 필요");
            found = true;
            return [line, ...defaults(expected)];
          }
        }
        return inAgents && /^\s*default_subagent_(?:model|reasoning_effort)\s*=/.test(line) ? [] : [line];
      }).join("\n");
      if (!found) content = `${actual.trimEnd()}\n\n[agents]\n${defaults(expected).join("\n")}\n`;
    }
    return { target, actual, content };
  });
  for (const { target, actual, content } of changes) {
    if (actual !== content) {
      mkdirSync(path.dirname(target), { recursive: true });
      writeFileSync(target, content);
    }
  }
}

export function assign(table, { client, tier, effort, role, reason, snapshot, evaluate = false, now = new Date(), env = process.env }) {
  validate(table);
  const c = table.clients[client];
  const m = c?.models[tier];
  if (!m) throw Error("client/등급 미지원");
  if (!["implement", "review", "investigate", "document"].includes(role) || typeof reason !== "string" || !reason.trim()) throw Error("역할과 모델/강도 선택 근거 명시 필요");
  const age = (now - new Date(`${c.checkedAt}T00:00:00Z`)) / 86400000;
  if (age < 0 || age >= table.refreshDays) throw Error("stale: 선택표 재확인 필요");
  if (!snapshot || snapshot.client !== client || snapshot.version !== c.version || snapshot.context !== c.context) throw Error("계정/공급자/클라이언트 변경 또는 snapshot 누락: 재확인 필요");
  const observedAge = (now - new Date(snapshot.observedAt)) / 86400000;
  if (!Number.isFinite(observedAge) || observedAge < 0 || observedAge >= 1) throw Error("snapshot은 24시간 이내 현재 계정/클라이언트 증거여야 함");
  const available = snapshot.models?.find((a) => a.model === m.model);
  const expectedModel = client.startsWith("codex") ? m.model : m.resolvedModel;
  if (!available || available.blocked || !available.actualModel || (expectedModel ? available.actualModel !== expectedModel : !available.actualModel.startsWith(`claude-${m.model}-`))) throw Error("모델 누락/차단/실제 모델 불일치; 부모 fallback 금지");
  if (effort === undefined || (effort !== "none" && !efforts.includes(effort))) throw Error("배정 effort 명시 필요; 묵시 상속 금지");
  if (effort === "none" ? m.defaultEffort !== null || available.efforts?.length !== 0 : !m.efforts.includes(effort) || !available.efforts?.includes(effort)) throw Error("미지원 effort; 모델 변경 뒤 effort 재선택 필요");
  if (client === "claude-cli" && env.CLAUDE_CODE_SUBAGENT_MODEL) throw Error("CLAUDE_CODE_SUBAGENT_MODEL 충돌: 실제 모델 확인 전 실행 금지");
  if (!evaluate && (m.capability !== "confirmed" || m.evaluation === "pending" || m.nativeExecution === "pending")) throw Error("실행 검증 미완료: --evaluate로 대표 평가 후 선택표 갱신");
  return {
    client, tier, role, reason, model: m.model, actualModel: available.actualModel, effort, checkedAt: c.checkedAt,
    evaluation: evaluate ? "evaluation-only; 품질/비용/native 실행 미검증 항목은 증거로 별도 확인" : m.evaluation,
    nativeAgent: { name: `task-${tier}`, verified: m.nativeExecution === "native-confirmed", defaultEffort: m.defaultEffort, evidence: m.executionEvidence ?? "pending; 실제 agent 경로 미검증" },
    invocation: client === "codex-desktop" ? { model: m.model, reasoning_effort: effort, fork_turns: "none" } : client === "codex-cli" ? { argv: ["exec", "--strict-config", "--model", m.model, "-c", `model_reasoning_effort=${quote(effort)}`], instructions: instruction } : { ...(m.nativeExecution === "native-confirmed" ? { agent: `task-${tier}` } : {}), model: m.model, ...(effort === "none" ? {} : { effort }), instructions: instruction },
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
    const [command, ...args] = process.argv.slice(2);
    const table = validate(JSON.parse(readFileSync(path.join(root, TABLE), "utf8")));
    if (command === "sync") {
      sync(root, table);
      console.log("양쪽 native 설정 동기화 완료");
    } else {
      const drift = check(root, table);
      if (drift.length) throw Error(drift.join("\n"));
      if (command === "check") console.log("모델 선택표·native 설정 정합성 통과 (최신성/실행 평가는 배정 시 확인)");
      else if (command === "assign") {
        const options = {};
        for (let i = 0; i < args.length; i++) {
          if (args[i] === "--evaluate") options.evaluate = true;
          else if (["--client", "--tier", "--effort", "--role", "--reason", "--snapshot"].includes(args[i]) && args[i + 1] && !args[i + 1].startsWith("--")) options[args[i++].slice(2)] = args[i];
          else throw Error(`알 수 없거나 값이 없는 인자: ${args[i]}`);
        }
        if (options.snapshot) options.snapshot = JSON.parse(readFileSync(options.snapshot, "utf8"));
        console.log(JSON.stringify(assign(table, options), null, 2));
      } else throw Error("사용: agent-models.mjs check | sync | assign --client <surface> --tier <grade> --effort <level> --role implement|review|investigate|document --reason <선택 근거> --snapshot <현재 증거.json> [--evaluate]");
    }
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
